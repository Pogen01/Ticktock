"""End-to-end pipeline: dataset -> models -> scorecards -> saved artifacts.

    python scripts/run_pipeline.py

1. Build the waiting-time dataset (data/processed/orders.parquet).
2. Fit every model on train (2006-2019 starts) and score on tune (2020-2021).
3. Refit on everything whose outcome is known before 2022, score once on the
   test period (Jan 2022 - Oct 2026).
4. Save models (models/*.pkl), reports (reports/*.csv|json) and EXPERIMENTS.md.
"""

from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from ticktock import config  # noqa: E402
from ticktock.compare import build_comparison  # noqa: E402
from ticktock.dataset import build_dataset, save_dataset  # noqa: E402
from ticktock.evaluate import full_report, reliability, scorecard  # noqa: E402
from ticktock.features import BASE_FEATURES, SECTOR_FEATURES  # noqa: E402
from ticktock.models import (InverseGaussianTheory, InverseGaussianTraffic,  # noqa: E402
                             KaplanMeier, WeibullAFT, save_model)

FEATURE_SETS = {
    "kaplan_meier": "distance (vol units) x traffic tercile x side",
    "ig_theory": "distance, trailing volatility",
    "ig_traffic": "distance, volatility rescaled by traffic, market stress, calendar, risk, sector",
    "weibull_no_risk": "distance, volatility, traffic, trend, market, calendar",
    "weibull_aft": "all of the above + risk-factor themes (2024 text before 2024) + sector",
}


def make_models():
    return [KaplanMeier(), InverseGaussianTheory(), InverseGaussianTraffic(),
            WeibullAFT(features=BASE_FEATURES, name="weibull_no_risk"),
            WeibullAFT()]


def final_train_mask(df: pd.DataFrame) -> pd.Series:
    """Starts whose whole outcome window closes before the first test session."""
    days = pd.Index(sorted(df["date"].unique()))
    first_test = days[days >= config.SPLITS["test"][0]][0]
    cutoff = days[days.get_loc(first_test) - config.HORIZON]
    return df["date"] <= cutoff


def fmt(x, nd=3):
    return f"{x:.{nd}f}"


def write_experiments(tune: pd.DataFrame, test: pd.DataFrame, n_train: int, n_final: int):
    lines = [
        "# Experiment log",
        "",
        f"Generated by `scripts/run_pipeline.py` on {date.today().isoformat()}. Seed {config.SEED}.",
        f"Units: trading days. Horizon {config.HORIZON} days. Distances {config.DISTANCES_PCT} %.",
        "Fill rule: next sessions' low <= limit - $0.01 (buy) / high >= limit + $0.01 (sell).",
        "",
        "Coverage targets are 0.50 and 0.80. Lower Brier is better; higher censored LL is better.",
        "Accuracy = share of orders where the yes/no call \"fills within t days\" (yes when the "
        "model's probability >= 50%) was right, averaged over t = 1, 5, 10, 20 days. "
        "Baseline = always give the most common answer.",
        "",
        "| ID | Model | Features | Trained on | Scored on | Accuracy | Baseline | Acc@10d "
        "| 50% cov. | 80% cov. | Brier@5d | Brier@20d | Censored LL | ms/pred |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    i = 1
    for label, tab, trained in ((f"tune ({config.SPLIT_LABELS['tune']})", tune,
                                 f"train, {n_train:,} orders"),
                                (f"test ({config.SPLIT_LABELS['test']})", test,
                                 f"train+tune, {n_final:,} orders")):
        for _, r in tab.iterrows():
            lines.append(
                f"| E{i:02d} | {r['model']} | {FEATURE_SETS[r['model']]} | {trained} | {label} "
                f"| {r['accuracy']:.1%} | {r['accuracy_base']:.1%} | {r['acc@10d']:.1%} "
                f"| {fmt(r['cov50%'])} | {fmt(r['cov80%'])} | {fmt(r['brier@5d'], 4)} "
                f"| {fmt(r['brier@20d'], 4)} | {fmt(r['censored_ll'], 4)} "
                f"| {fmt(r['ms_per_pred'], 4)} |")
            i += 1
    lines += ["", "Slices of the test period (years, 2022 bear market, April 2025, traffic levels, "
              "events) are in `reports/test_slices.csv`; the COVID crash is a slice of the tune "
              "set in `reports/tune_slices.csv`."]
    (config.ROOT / "EXPERIMENTS.md").write_text("\n".join(lines) + "\n")


def main():
    np.random.seed(config.SEED)
    config.REPORTS_DIR.mkdir(exist_ok=True)
    print("1/4 building dataset ...")
    df = build_dataset()
    print("   ", save_dataset(df), f"{len(df):,} orders")
    print(df.groupby("split").size().to_string())

    train = df[df["split"] == "train"]
    tune = df[df["split"] == "tune"]
    test = df[df["split"] == "test"]
    traffic_edges = np.quantile(train["traffic5"], [1 / 3, 2 / 3])

    print("2/4 fit on train, score on tune ...")
    tune_models = [m.fit(train) for m in make_models()]
    tune_rows = [scorecard(m, tune) for m in tune_models]
    tune_tab = pd.DataFrame(tune_rows)
    print(tune_tab.round(4).to_string(index=False))
    tune_tab.to_csv(config.REPORTS_DIR / "tune_scorecard.csv", index=False)
    full_report(tune_models, tune, traffic_edges).to_csv(config.REPORTS_DIR / "tune_slices.csv",
                                                         index=False)

    print(f"3/4 refit on train+tune, score once on the test period ({config.SPLIT_LABELS['test']}) ...")
    final = df[final_train_mask(df)]
    models = [m.fit(final) for m in make_models()]
    test_tab = pd.DataFrame([scorecard(m, test) for m in models])
    print(test_tab.round(4).to_string(index=False))
    test_tab.to_csv(config.REPORTS_DIR / "test_scorecard.csv", index=False)
    full_report(models, test, traffic_edges).to_csv(config.REPORTS_DIR / "test_slices.csv",
                                                    index=False)

    rel = {m.name: {f"{t}d": reliability(m.predict_cdf(test), test["wait"].to_numpy(),
                                         test["filled"].to_numpy(), test["observed"].to_numpy(), t)
                    for t in (5, 20)} for m in models}
    (config.REPORTS_DIR / "reliability.json").write_text(json.dumps(rel, indent=1))
    (config.REPORTS_DIR / "comparison.json").write_text(
        json.dumps(build_comparison(models, test), separators=(",", ":")))

    wb = next(m for m in models if m.name == "weibull_aft")
    wb.coefficients().rename("beta").to_csv(config.REPORTS_DIR / "weibull_coefficients.csv")
    next(m for m in models if m.name == "ig_traffic").coefficients().rename("beta").to_csv(
        config.REPORTS_DIR / "ig_traffic_coefficients.csv")

    print("4/4 saving models ...")
    for m in models:
        save_model(m)
    # Default model in the demo: most accurate on the tune set (never on test).
    best = tune_tab.sort_values("accuracy", ascending=False)["model"].iloc[0]
    meta = {"traffic_edges": traffic_edges.tolist(), "horizon": config.HORIZON,
            "trained_through": str(final["date"].max().date()),
            "first_test_date": str(test["date"].min().date()),
            "last_test_date": str(test["date"].max().date()),
            "split_labels": config.SPLIT_LABELS,
            "n_orders": {k: int(v) for k, v in df["split"].value_counts().items()},
            "models": [m.name for m in models], "default_model": best}
    (config.MODELS_DIR / "meta.json").write_text(json.dumps(meta, indent=1))
    write_experiments(tune_tab, test_tab, len(train), len(final))
    print("done.")


if __name__ == "__main__":
    main()
